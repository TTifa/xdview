/// 计算 MD5 摘要。
pub fn digest(input: &[u8]) -> [u8; 16] {
    let mut state = [0x6745_2301u32, 0xefcd_ab89, 0x98ba_dcfe, 0x1032_5476];

    // 填充：1 个 0x80，补 0 到 56 mod 64，末尾 8 字节小端比特长度
    let mut msg = input.to_vec();
    let bit_len = (input.len() as u64).wrapping_mul(8);
    msg.push(0x80);
    while msg.len() % 64 != 56 {
        msg.push(0);
    }
    msg.extend_from_slice(&bit_len.to_le_bytes());

    for chunk in msg.chunks_exact(64) {
        let mut m = [0u32; 16];
        for (i, word) in m.iter_mut().enumerate() {
            *word = u32::from_le_bytes([
                chunk[i * 4],
                chunk[i * 4 + 1],
                chunk[i * 4 + 2],
                chunk[i * 4 + 3],
            ]);
        }

        let [mut a, mut b, mut c, mut d] = state;
        for i in 0..64 {
            let (f, g) = match i / 16 {
                0 => ((b & c) | (!b & d), i),
                1 => ((d & b) | (!d & c), (5 * i + 1) % 16),
                2 => (b ^ c ^ d, (3 * i + 5) % 16),
                _ => (c ^ (b | !d), (7 * i) % 16),
            };
            let tmp = d;
            d = c;
            c = b;
            let sum = a.wrapping_add(f).wrapping_add(K[i]).wrapping_add(m[g]);
            b = b.wrapping_add(sum.rotate_left(S[i]));
            a = tmp;
        }
        state[0] = state[0].wrapping_add(a);
        state[1] = state[1].wrapping_add(b);
        state[2] = state[2].wrapping_add(c);
        state[3] = state[3].wrapping_add(d);
    }

    let mut out = [0u8; 16];
    for (i, word) in state.iter().enumerate() {
        out[i * 4..i * 4 + 4].copy_from_slice(&word.to_le_bytes());
    }
    out
}

/// 小写十六进制摘要，Digest 鉴权要的格式。
pub fn hex_digest(input: &[u8]) -> String {
    let mut s = String::with_capacity(32);
    for b in digest(input) {
        s.push_str(&format!("{b:02x}"));
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rfc1321_vectors() {
        assert_eq!(hex_digest(b""), "d41d8cd98f00b204e9800998ecf8427e");
        assert_eq!(hex_digest(b"a"), "0cc175b9c0f1b6a831c399e269772661");
        assert_eq!(hex_digest(b"abc"), "900150983cd24fb0d6963f7d28e17f72");
        assert_eq!(
            hex_digest(b"message digest"),
            "f96b697d7cb7938d525a2f31aaf161d0"
        );
        assert_eq!(
            hex_digest(b"abcdefghijklmnopqrstuvwxyz"),
            "c3fcd3d76192e4007dfb496cca67e13b"
        );
    }

    #[test]
    fn block_boundaries() {
        // 55/56/63/64 正好覆盖「补齐不跨块 / 补满一块 / 差一字节 / 正好一块」四种情况
        assert_eq!(hex_digest(&[b'x'; 55]), "04364420e25c512fd958a70738aa8f72");
        assert_eq!(hex_digest(&[b'x'; 56]), "668a72d5ba17f08e62dabcafad6db14b");
        assert_eq!(hex_digest(&[b'x'; 63]), "7dc2ca208106a2f703567bdff99d8981");
        assert_eq!(hex_digest(&[b'x'; 64]), "c1bb4f81d892b2d57947682aeb252456");
        assert_eq!(
            hex_digest(&[b'x'; 1000]),
            "398533d48111e9f664b1f64cb10c4b63"
        );
    }

    #[test]
    fn empty_and_padding_differ() {
        assert_ne!(hex_digest(b""), hex_digest(&[0u8]));
    }
}
